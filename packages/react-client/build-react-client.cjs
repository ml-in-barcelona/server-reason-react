/*
 * Generates dist/: React's `react-client` package, exactly as React's own build emits it.
 *
 * React doesn't publish react-client, so we build it from source: run-react-build.cjs runs
 * React's own rollup build (pointing the `react-client/flight` entry at our flight-entry.js,
 * which re-exports both the response and reply clients), and this script copies the build
 * output into dist/ and writes the package manifest for it.
 *
 * We deliberately do NOT bundle the output into a single file. React's flight.js selects
 * between the development and production builds at `process.env.NODE_ENV`, and bundling
 * resolved that condition at *generation* time — which silently dropped the production build
 * and shipped the 158KB dev client to every consumer. Shipping the package as-is leaves the
 * choice to the consumer's bundler, which picks one branch (production is 63KB) and
 * tree-shakes the other. `react` stays a plain require, resolved by the consumer.
 *
 * Run via `npm run react-client-generate` (or `make react-client-generate`). dist/ is
 * COMMITTED; regenerate it only when bumping the React submodule. Consumers use the committed
 * files, so building server-reason-react needs neither Node nor the submodule — only
 * regeneration does.
 */
const path = require("path");
const fs = require("fs");
const os = require("os");
const { execFileSync } = require("child_process");

const dir = __dirname;
const reactDir = path.join(dir, "react");
const outDir = path.join(dir, "dist");

/* React's build runs `npm pack` (and we may run `yarn`), which write to ~/.npm and
   ~/.cache. Point HOME at a fresh temp dir so it also works inside restricted sandboxes. */
const env = { ...process.env, HOME: fs.mkdtempSync(path.join(os.tmpdir(), "srr-react-build-")) };

if (!fs.existsSync(path.join(reactDir, "package.json"))) {
  console.error(`react submodule not checked out at ${reactDir}
       run: make submodules`);
  process.exit(1);
}

/* Install React's dev toolchain (rollup, babel, ...) once. */
if (!fs.existsSync(path.join(reactDir, "node_modules", ".bin"))) {
  execFileSync("yarn", ["install", "--frozen-lockfile"], { cwd: reactDir, stdio: "inherit", env });
}

/* Run React's rollup build in a child process and wait for it (its exit is the
   "build done" signal; execFileSync throws if it failed). */
execFileSync(process.execPath, [path.join(dir, "run-react-build.cjs")], { stdio: "inherit", env });

const built = path.join(reactDir, "build/node_modules/react-client");

/* The version is derived from the submodule, never maintained by hand: the package this
   installs is the Flight client of exactly this React, and the peer range must match it. */
const reactVersionSource = fs.readFileSync(
  path.join(reactDir, "packages/shared/ReactVersion.js"),
  "utf8"
);
const reactVersion = /^export default '(.*)';$/m.exec(reactVersionSource)?.[1];
if (!reactVersion) {
  console.error(`could not read the React version from ${reactDir}/packages/shared/ReactVersion.js`);
  process.exit(1);
}

/* Copy React's build output verbatim — no transformation, no bundling. */
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(path.join(outDir, "cjs"), { recursive: true });
for (const file of [
  "flight.js",
  "LICENSE",
  "cjs/react-client-flight.development.js",
  "cjs/react-client-flight.production.js",
]) {
  fs.copyFileSync(path.join(built, file), path.join(outDir, file));
}

/* The manifest consumers see through their `file:` dependency. React's own package.json is
   not reused: it names the package `react-client`, and pins `react` at ^17. */
const manifest = {
  name: "@ml-in-barcelona/react-client",
  version: reactVersion,
  description:
    "React's Flight client (react-client/flight), built from React at the commit pinned by " +
    "server-reason-react's submodule. React does not publish react-client; this is not part " +
    "of React's public API and its shape may change between React releases.",
  license: "MIT",
  private: true,
  homepage: "https://github.com/ml-in-barcelona/server-reason-react",
  repository: {
    type: "git",
    url: "https://github.com/ml-in-barcelona/server-reason-react.git",
    directory: "packages/react-client",
  },
  main: "./flight.js",
  exports: { ".": "./flight.js" },
  peerDependencies: { react: `^${reactVersion}` },
};

fs.writeFileSync(
  path.join(outDir, "package.json"),
  JSON.stringify(manifest, null, 2) + "\n"
);

fs.writeFileSync(
  path.join(outDir, "README.md"),
  `# @ml-in-barcelona/react-client

Do not edit by hand. Generated by \`make react-client-generate\` from React ${reactVersion}
(\`packages/react-client/react\`), which is React's own build output for its unpublished
\`react-client\` package. See ../README.md.
`
);

console.log(`dist/ written from React ${reactVersion}`);
